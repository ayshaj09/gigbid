"""Regenerate the README / report results tables from evals/results/*.json (latest file per kind).

    python -m evals.runners.results_table   -> evals/results/results_table.md

Tables: (1) B5 per variant, all personas pooled: retrieval from rag_*.json; unsupported claims,
p95 latency, GigSim reply rate and cost come from the decision / outcome runs, which exist only for
the shipped variant (others are "-"). Judge score is "-" until a calibrated judge run exists.
(2) retrieval per persona. (3) V8 ablation. (4) decisions per persona.
"""
from __future__ import annotations

import json
from statistics import mean

from agent.config import ROOT, load_config

RES = ROOT / "evals" / "results"
PERSONAS = ["ai_engineer", "web_fullstack", "data_analyst"]


def latest(pattern: str):
    files = sorted(RES.glob(pattern))
    return (json.loads(files[-1].read_text(encoding="utf-8")), files[-1].name) if files else (None, None)


def fmt(x, nd=3):
    return "-" if x is None else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


def main():
    shipped = load_config()["retrieval"]["variant"]
    rag = {p: latest(f"rag_dev_{p}_*.json") for p in PERSONAS}
    dec = {p: latest(f"decision_dev_{p}_*.json") for p in PERSONAS}
    out_runs = {p: latest(f"gigsim_outcomes_dev_{p}_writer_*.json") for p in PERSONAS}
    judge, judge_f = latest("judge_scores_*.json")
    cites = sorted({f for d in (rag, dec, out_runs) for _, f in d.values() if f} | ({judge_f} if judge_f else set()))

    variants = []
    for p in PERSONAS:
        d = rag[p][0]
        if d:
            variants = [v for v in d["results"] if "-minus-" not in v]
            break

    def pooled(v, m):
        vals = [(rag[p][0]["results"][v]["overall"][m], rag[p][0]["results"][v]["overall"]["n"])
                for p in PERSONAS if rag[p][0] and v in rag[p][0]["results"]]
        n = sum(w for _, w in vals)
        return sum(x * w for x, w in vals) / n if n else None

    decs = [dec[p][0]["summary"] for p in PERSONAS if dec[p][0]]
    outs = [out_runs[p][0] for p in PERSONAS if out_runs[p][0]]
    unsupported = mean(s["unsupported_per_proposal_after"] for s in decs if s["unsupported_per_proposal_after"] is not None) if decs else None
    unsupported_before = mean(s["unsupported_per_proposal_before"] for s in decs if s["unsupported_per_proposal_before"] is not None) if decs else None
    p95 = max(s["p95_latency_s_per_job"] for s in decs) if decs else None
    bids = sum(o["n_bids"] for o in outs)
    reply = sum(o["reply_rate"] * o["n_bids"] for o in outs) / bids if bids else None
    usd = max((s.get("usd_per_proposal") or s.get("usd_per_job") or 0.0) for s in decs) if decs else None

    L = [f"_Generated by `python -m evals.runners.results_table`; sources: {', '.join(f'`{c}`' for c in cites)}._", "",
         "### B5: variants (three personas pooled, silver relevance labels)", "",
         "| Variant | Evidence Recall@5 | nDCG@10 | MRR | Unsupported claims / proposal (after verification) | Judge score | GigSim reply rate | p95 latency per job (s) | Cost / proposal (USD) |",
         "|---|---|---|---|---|---|---|---|---|"]
    for v in variants:
        is_ship = v == shipped
        L.append(f"| {v}{' (shipped)' if is_ship else ''} | {fmt(pooled(v, 'recall@5'))} | {fmt(pooled(v, 'ndcg@10'))} | {fmt(pooled(v, 'mrr'))} | "
                 f"{fmt(unsupported, 2) + f' (before: {unsupported_before:.2f})' if is_ship and unsupported is not None else '-'} | "
                 f"{fmt(judge.get('mean_score'), 2) if is_ship and judge else '-'} | "
                 f"{fmt(reply, 3) + f' ({bids} bids)' if is_ship and reply is not None else '-'} | "
                 f"{fmt(p95, 2) if is_ship else '-'} | {fmt(usd, 4) if is_ship else '-'} |")
    L += ["", "### Retrieval per persona (Recall@5 / nDCG@10; jobs with 4+ requirements in brackets)", "",
          "| Variant | " + " | ".join(PERSONAS) + " |", "|---|" + "---|" * len(PERSONAS)]
    for v in variants:
        cells = []
        for p in PERSONAS:
            d = rag[p][0]
            if not d or v not in d["results"]:
                cells.append("-")
                continue
            o, m = d["results"][v]["overall"], d["results"][v].get("jobs_with_4plus_requirements") or {}
            cells.append(f"{o['recall@5']:.3f} / {o['ndcg@10']:.3f} [{fmt(m.get('recall@5'))}]")
        L.append(f"| {v} | " + " | ".join(cells) + " |")
    abl = sorted({v for p in PERSONAS if rag[p][0] for v in rag[p][0]["results"] if "-minus-" in v})
    if abl:
        L += ["", "### Ablation of V8 (one component removed at a time; pooled)", "", "| Variant | Recall@5 | nDCG@10 | MRR |", "|---|---|---|---|"]
        for v in abl:
            L.append(f"| {v} | {fmt(pooled(v, 'recall@5'))} | {fmt(pooled(v, 'ndcg@10'))} | {fmt(pooled(v, 'mrr'))} |")
    L += ["", "### Decisions per persona (shipped config)", "",
          "| Persona | bid/skip F1 | scam precision | scam recall | injections followed | price in fair band | unsupported before → after | p95 s/job | GigSim reply rate (bids) | hire rate |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for p in PERSONAS:
        s = dec[p][0]["summary"] if dec[p][0] else None
        o = out_runs[p][0]
        if not s:
            continue
        L.append(f"| {p} | {fmt(s['bid_skip_f1'])} | {fmt(s['scam_precision'])} | {fmt(s['scam_recall'])} | {s['injections_followed']} | "
                 f"{fmt(s['price_in_fair_band'])} | {fmt(s['unsupported_per_proposal_before'], 2)} → {fmt(s['unsupported_per_proposal_after'], 2)} | "
                 f"{fmt(s['p95_latency_s_per_job'], 2)} | {fmt(o['reply_rate']) + ' (' + str(o['n_bids']) + ')' if o else '-'} | {fmt(o['hire_rate']) if o else '-'} |")
    text = "\n".join(L) + "\n"
    (RES / "results_table.md").write_text(text, encoding="utf-8")
    print(text.encode("ascii", "replace").decode())


if __name__ == "__main__":
    main()
